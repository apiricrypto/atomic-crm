-- Transactions record cash movement and settle exactly one source ledger.
-- Procurement commitments and project contract snapshots never post here directly.
create table public.financial_transactions (
    id bigint generated by default as identity primary key,
    receivable_id bigint,
    payable_id bigint,
    reference text not null unique,
    direction text not null,
    amount bigint not null,
    currency text not null,
    occurred_at timestamp with time zone not null,
    method text not null,
    notes text,
    created_at timestamp with time zone not null default now(),
    sales_id bigint,
    constraint financial_transactions_direction_check check (
        direction in ('inflow', 'outflow')
    ),
    constraint financial_transactions_method_check check (
        method in ('bank', 'cash', 'card', 'cheque', 'other')
    ),
    constraint financial_transactions_amount_check check (amount > 0),
    constraint financial_transactions_currency_check check (currency ~ '^[A-Z]{3}$'),
    constraint financial_transactions_source_direction_check check (
        (receivable_id is not null and payable_id is null and direction = 'inflow')
        or
        (receivable_id is null and payable_id is not null and direction = 'outflow')
    )
);

