-- Append-only observations transcribed by an authorized user from an official
-- SETAD browser session. Keeping these rows separate preserves both the Radar
-- assertion and the official observation when they conflict.
create table public.tender_setad_verifications (
    id bigint generated by default as identity primary key,
    opportunity_id bigint not null,
    opportunity_type text not null,
    official_need_no text,
    official_tender_no text,
    title text not null,
    description text,
    organizer text,
    province text,
    city text,
    publish_date date,
    document_deadline date,
    submission_deadline date,
    official_source_url text not null,
    verification_status text not null,
    checked_by_sales_id bigint not null,
    checked_at timestamp with time zone not null default now(),
    constraint tender_setad_verifications_type_check check (
        opportunity_type in ('inquiry', 'tender')
    ),
    constraint tender_setad_verifications_identifier_check check (
        (opportunity_type = 'inquiry'
            and official_need_no is not null
            and official_tender_no is null)
        or
        (opportunity_type = 'tender'
            and official_tender_no is not null
            and official_need_no is null)
    ),
    constraint tender_setad_verifications_title_check check (
        length(btrim(title)) > 0
    ),
    constraint tender_setad_verifications_status_check check (
        verification_status in ('setad_verified', 'data_conflict')
    ),
    constraint tender_setad_verifications_url_check check (
        (opportunity_type = 'inquiry'
            and official_source_url = 'https://eproc.setadiran.ir/eproc/entry.do')
        or
        (opportunity_type = 'tender'
            and official_source_url = 'https://etend.setadiran.ir/etend/index.action')
    )
);

-- Audit events are append-only and deliberately exclude credentials, cookies,
-- OTP values, CAPTCHA material and raw provider payloads.
create table public.tender_audit_log (
    id bigint generated by default as identity primary key,
    opportunity_id bigint,
    event_type text not null,
    actor_sales_id bigint not null,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamp with time zone not null default now(),
    constraint tender_audit_log_event_check check (length(btrim(event_type)) > 0),
    constraint tender_audit_log_metadata_check check (jsonb_typeof(metadata) = 'object'),
    constraint tender_audit_log_sensitive_keys_check check (
        not (
            metadata ? 'password'
            or metadata ? 'credential'
            or metadata ? 'cookie'
            or metadata ? 'captcha'
            or metadata ? 'otp'
            or metadata ? 'token'
            or metadata ? 'raw_payload'
        )
    )
);

