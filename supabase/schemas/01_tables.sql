-- Tender records are created only after explicit review/import from Lead Inbox.
-- SETAD identifiers, aggregator identity, publication dates and deadlines remain
-- separate so a copied or inferred value cannot silently become official truth.
create table public.tender_opportunities (
    id bigint generated by default as identity primary key,
    lead_id bigint not null unique,
    source text not null,
    aggregator_record_id text,
    opportunity_type text not null,
    official_need_no text,
    official_tender_no text,
    title text not null,
    description text,
    organizer text,
    province text,
    city text,
    publish_date date,
    document_deadline date,
    submission_deadline date,
    official_source_url text,
    aggregator_source_url text,
    domain text not null,
    trade text,
    category text,
    verification_status text not null default 'pending_setad_verification',
    radar_score smallint,
    radar_grade text,
    fallback_fingerprint text not null,
    assigned_sales_id bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint tender_opportunities_source_check check (
        source in ('tender_radar', 'setad', 'manual')
    ),
    constraint tender_opportunities_type_check check (
        opportunity_type in ('inquiry', 'tender')
    ),
    constraint tender_opportunities_official_identifier_check check (
        (opportunity_type = 'inquiry' and official_tender_no is null)
        or
        (opportunity_type = 'tender' and official_need_no is null)
    ),
    constraint tender_opportunities_need_no_check check (
        official_need_no is null or length(btrim(official_need_no)) > 0
    ),
    constraint tender_opportunities_tender_no_check check (
        official_tender_no is null or length(btrim(official_tender_no)) > 0
    ),
    constraint tender_opportunities_aggregator_id_check check (
        aggregator_record_id is null or length(btrim(aggregator_record_id)) > 0
    ),
    constraint tender_opportunities_domain_check check (
        domain in ('renewable_energy', 'security_systems')
    ),
    constraint tender_opportunities_verification_check check (
        verification_status in (
            'setad_verified',
            'pending_setad_verification',
            'data_conflict'
        )
    ),
    constraint tender_opportunities_radar_pair_check check (
        (radar_score is null and radar_grade is null)
        or
        (radar_score between 0 and 100 and radar_grade in ('A', 'B', 'C'))
    ),
    constraint tender_opportunities_official_url_check check (
        official_source_url is null or official_source_url ~ '^https://(eproc|etend)\.setadiran\.ir/'
    ),
    constraint tender_opportunities_aggregator_url_check check (
        aggregator_source_url is null or aggregator_source_url ~ '^https?://'
    ),
    constraint tender_opportunities_fingerprint_check check (
        length(btrim(fallback_fingerprint)) > 0
    )
);

