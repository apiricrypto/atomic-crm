-- Inbound leads remain quarantined from core CRM records. Integrations write
-- here through server-side credentials; authenticated staff may triage only
-- the normalized fields exposed by the product.
create table public.lead_inbox (
    id bigint generated by default as identity primary key,
    source text not null,
    source_record_id text not null,
    source_url text,
    title text not null,
    organization_name text,
    contact_name text,
    contact_phone text,
    contact_email extensions.citext,
    province text,
    city text,
    description text,
    estimated_amount bigint,
    estimated_currency text,
    deadline date,
    status text not null default 'new',
    priority text not null default 'normal',
    raw_payload jsonb not null default '{}'::jsonb,
    captured_at timestamp with time zone not null,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    assigned_sales_id bigint,
    constraint lead_inbox_source_check check (
        source in ('tender_radar', 'bale_market', 'website', 'manual', 'import')
    ),
    constraint lead_inbox_source_record_id_check check (length(btrim(source_record_id)) > 0),
    constraint lead_inbox_title_check check (length(btrim(title)) > 0),
    constraint lead_inbox_source_url_check check (
        source_url is null or source_url ~ '^https?://'
    ),
    constraint lead_inbox_status_check check (
        status in ('new', 'reviewing', 'qualified', 'rejected', 'converted')
    ),
    constraint lead_inbox_priority_check check (
        priority in ('low', 'normal', 'high', 'urgent')
    ),
    constraint lead_inbox_raw_payload_check check (jsonb_typeof(raw_payload) = 'object'),
    constraint lead_inbox_estimate_check check (
        (estimated_amount is null and estimated_currency is null)
        or
        (estimated_amount >= 0 and estimated_currency ~ '^[A-Z]{3}$')
    ),
    constraint lead_inbox_source_record_key unique (source, source_record_id)
);

